function keywordExplanation(examId, question, choice) {
  const specific = specificChoiceExplanations[examId]?.[question.number]?.[choice.id];
  if (specific) return specific;
  const key = questionKeys[examId]?.[question.number];
  if (!key) throw new Error(`Missing reviewed question key for ${examId} Q${question.number}.`);
  const answerIds = new Set(String(question.answer ?? "").toLowerCase().split("|"));
  const isCorrect = answerIds.has(String(choice.id).toLowerCase());
  // Set B's choice-bank entries use numeric IDs (1–20), which overlap with
  // ordinary multiple-choice IDs. Their definitions are only valid for the
  // shared bank in Q31–Q35, never for a regular question with the same ID.
  const bankDefinition = question.type === "choice_bank"
    ? choiceBankDefinitions[examId]?.[String(choice.id)]
    : undefined;
  if (bankDefinition) {
    return `${bankDefinition} ${isCorrect ? "이 문항이 묻는 항목과 일치한다." : "이 문항이 묻는 항목과는 일치하지 않는다."}`;
  }
  const optionNote = optionKeywords.find(([pattern]) => pattern.test(choice.text))?.[1];
  return `${optionNote ? `${optionNote} ` : ""}${key} ${isCorrect ? "따라서 이 선택지가 문항의 기준에 맞는다." : "따라서 이 선택지는 문항의 기준과 다르다."}`;
}

let stale = false;
for (const id of ["public-set-a", "public-set-b"]) {
  const manifestPath = resolve(contentRoot, "data/web-exams", `${id}.json`);
  const current = readFileSync(manifestPath, "utf8");
  const exam = JSON.parse(current);
  for (const question of exam.questions) {
    const metadata = publicQuestionMetadata[id]?.[question.number];
    if (metadata) [question.chapter, question.topic] = metadata;
    if (!choiceTypes.has(question.type)) continue;
    delete question.explanation;
    for (const choice of question.choices ?? []) choice.feedback = { explanation: keywordExplanation(id, question, choice) };
  }
  const next = `${JSON.stringify(exam, null, 2)}\n`;
  if (next !== current) {
    stale = true;
    if (!checkOnly) writeFileSync(manifestPath, next, "utf8");
  }
}

if (checkOnly && stale) {
  console.error("Public choice feedback is out of date. Run: node tools/normalize-aipot-public-choice-feedback.mjs");
  process.exit(1);
}
console.log(checkOnly ? "Public choice feedback is current." : "Public choice feedback normalized.");
